#!/usr/bin/env python3
"""
generate_stack.py — generate the docker compose stack, telegraf config, and
Grafana dashboards for a 1-3 gateway Powerwall installation.

Reads gateways.json (written by setup.sh):

    {"gateways": [
        {"tag": "panel_a", "host": "192.168.1.100", "label": "Panel A"},
        {"tag": "panel_b", "host": "192.168.1.101", "label": "Panel B"}
    ]}

Passwords are NOT stored here — they live only in pypowerwall-<x>.env files.

Emits (relative to --out, default repo root):
    powerwall.yml            one pypowerwall service per gateway
    telegraf/telegraf.conf   one polling block per gateway
    grafana/dashboards/*.json  combined + per-gateway power-flow dashboards

Usage:
    python3 tools/generate_stack.py                 # from gateways.json
    python3 tools/generate_stack.py --count 3      # placeholder hosts (testing)
    python3 tools/generate_stack.py --out /tmp/x   # write elsewhere
Standard library only — runs on any python3 (or via the python docker image).
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_dashboards

REPO_ROOT = Path(__file__).resolve().parent.parent

GENERATED_NOTE = "GENERATED by tools/generate_stack.py — edit gateways.json and re-run (./setup.sh -g)"


def load_gateways(path):
    data = json.loads(Path(path).read_text())
    gws = data["gateways"]
    if not 1 <= len(gws) <= 3:
        raise SystemExit(f"gateways.json must define 1-3 gateways, found {len(gws)}")
    out = []
    for i, gw in enumerate(gws):
        letter = chr(ord("a") + i)
        expect = f"panel_{letter}"
        tag = gw.get("tag", expect)
        if tag != expect:
            raise SystemExit(f"gateway {i + 1} must use tag '{expect}' (found '{tag}')")
        out.append({
            "tag": tag,
            "letter": letter,
            "upper": letter.upper(),
            "host": gw.get("host", ""),
            "label": gw.get("label", f"Panel {letter.upper()}"),
            "port": 8675 + i,           # default host port (PW_<X>_PORT overrides)
        })
    return out


def placeholder_gateways(count):
    return [{"tag": f"panel_{chr(ord('a') + i)}", "letter": chr(ord("a") + i),
             "upper": chr(ord("A") + i), "host": f"192.168.1.{100 + i}",
             "label": f"Panel {chr(ord('A') + i)}", "port": 8675 + i}
            for i in range(count)]


def read_env(path):
    """Parse a KEY=VALUE env file into a dict (ignores comments/blanks)."""
    env = {}
    p = Path(path)
    if p.exists():
        for line in p.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    return env


