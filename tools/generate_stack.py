# ── telegraf.conf ─────────────────────────────────────────────────────────────

AGGREGATE_FIELDS = [
    ("load.instant_power", "home"),
    ("solar.instant_power", "solar"),
    ("battery.instant_power", "from_pw"),
    ("battery.instant_power", "to_pw"),
    ("site.instant_power", "from_grid"),
    ("site.instant_power", "to_grid"),
    ("load.instant_average_voltage", "home_voltage"),
    ("solar.instant_average_voltage", "solar_voltage"),
    ("battery.instant_average_voltage", "battery_voltage"),
    ("site.instant_average_voltage", "grid_voltage"),
    ("load.instant_average_current", "home_current"),
    ("solar.instant_average_current", "solar_current"),
    ("battery.instant_average_current", "battery_current"),
    ("site.instant_average_current", "grid_current"),
]

SIMPLE_ENDPOINTS = [
    ("/soe", "http", "battery state of charge (flattens to field \"percentage\")"),
    ("/strings", "strings", "solar string data"),
    ("/temps/pw", "pwtemps", "Powerwall temperatures"),
    ("/freq", "freq", "grid frequency and voltage"),
    ("/pod", "pod", "battery pod energy"),
    ("/fans/pw", "fans", "fan speeds"),
    ("/alerts/pw", "alerts", "alerts"),
]


def telegraf_gateway_block(gw):
    fields = "\n".join(
        f"""    [[inputs.http.json_v2.field]]
      path = "{path}"
      rename = "{rename}"
      type = "float\""""
        for path, rename in AGGREGATE_FIELDS)

    parts = [f"""# ══════════════════════════════════════════════════════════════════════════════
# {gw['label'].upper()}  (system={gw['tag']})
# ══════════════════════════════════════════════════════════════════════════════

# /aggregates — main power flows (json_v2 maps Tesla nested JSON → named fields)
[[inputs.http]]
  urls = ["http://pypowerwall-{gw['letter']}:8675/aggregates"]
  method = "GET"
  timeout = "5s"
  data_format = "json_v2"
  [[inputs.http.json_v2]]
    measurement_name = "http"
{fields}
  [inputs.http.tags]
    system = "{gw['tag']}"
"""]
    for path, name, desc in SIMPLE_ENDPOINTS:
        parts.append(f"""# {path} — {desc}
[[inputs.http]]
  urls = ["http://pypowerwall-{gw['letter']}:8675{path}"]
  method = "GET"
  timeout = "5s"
  data_format = "json"
  name_override = "{name}"
  [inputs.http.tags]
    system = "{gw['tag']}"
""")
    return "\n".join(parts)


def telegraf_conf(gateways):
    names = " and ".join(f"pypowerwall-{g['letter']} ({g['label']})" for g in gateways)
    tags = " / ".join(f"system={g['tag']}" for g in gateways)
    blocks = "\n".join(telegraf_gateway_block(g) for g in gateways)

    return f"""# {GENERATED_NOTE}
# telegraf.conf — Powerwall Dashboard ({len(gateways)} gateway{'s' if len(gateways) > 1 else ''})
# Polls {names} every 5 seconds.
# Each measurement is tagged with {tags}.
# Combined metrics are written by the enricher service, not Telegraf.

[agent]
  interval = "5s"
  round_interval = true
  metric_batch_size = 360
  metric_buffer_limit = 10000
  collection_jitter = "0s"
  flush_interval = "10s"
  flush_jitter = "0s"
  precision = ""
  hostname = ""
  omit_hostname = true
  log_with_timezone = "$TZ"

# ── InfluxDB output ────────────────────────────────────────────────────────────
[[outputs.influxdb]]
  urls = ["http://influxdb:8086"]
  database = "powerwall"
  retention_policy = "raw"
  skip_database_creation = false
  timeout = "5s"

{blocks}
# ── Power split processor ─────────────────────────────────────────────────────
# Tesla /aggregates reports a single SIGNED value for grid (site.instant_power)
# and battery (battery.instant_power). The json_v2 parser above copies each into
# two fields (from_*/to_*), so without this they would be identical. Split them
# into proper positive components:
#   from_grid = import (+site),  to_grid = export (-site)
#   from_pw   = discharge (+batt), to_pw  = charge (-batt)
# Only applies to the "http" measurement; /soe rows (percentage only) pass through.
[[processors.starlark]]
  namepass = ["http"]
  source = '''
def apply(metric):
    fg = metric.fields.get("from_grid")
    if fg != None:
        metric.fields["from_grid"] = max(0.0, fg)
        metric.fields["to_grid"] = max(0.0, -fg)
    fp = metric.fields.get("from_pw")
    if fp != None:
        metric.fields["from_pw"] = max(0.0, fp)
        metric.fields["to_pw"] = max(0.0, -fp)
    return metric
'''

# ── Date processors (add month/year tags for rollup queries) ──────────────────
[[processors.date]]
  tag_key = "month"
  date_format = "Jan"
  timezone = "$TZ"

[[processors.date]]
  tag_key = "year"
  date_format = "2006"
  timezone = "$TZ"

# ── System metrics (host health monitoring) ───────────────────────────────────
[[inputs.cpu]]
  percpu = true
  totalcpu = true
  collect_cpu_time = false
  report_active = false

[[inputs.disk]]
  ignore_fs = ["tmpfs", "devtmpfs", "devfs", "iso9660", "overlay", "aufs", "squashfs"]

[[inputs.diskio]]

[[inputs.mem]]

[[inputs.processes]]

[[inputs.system]]
"""


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gateways", default=str(REPO_ROOT / "gateways.json"),
                    help="path to gateways.json (default: repo root)")
    ap.add_argument("--count", type=int, choices=(1, 2, 3),
                    help="generate for N placeholder gateways instead of gateways.json")
    ap.add_argument("--out", default=str(REPO_ROOT),
                    help="output root directory (default: repo root)")
    ap.add_argument("--no-dashboards", action="store_true",
                    help="skip Grafana dashboard generation")
    args = ap.parse_args()

    if args.count:
        gateways = placeholder_gateways(args.count)
    else:
        gateways = load_gateways(args.gateways)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    compose_path = out / "powerwall.yml"
    compose_path.write_text(compose_yaml(gateways))
    print(f"Wrote {compose_path}")

    tconf = out / "telegraf" / "telegraf.conf"
    tconf.parent.mkdir(parents=True, exist_ok=True)
    tconf.write_text(telegraf_conf(gateways))
    print(f"Wrote {tconf}")

    if not args.no_dashboards:
        env = read_env(out / "compose.env")
        gen_dashboards.generate(
            gateways,
            rate_import=float(env.get("RATE_IMPORT", 0.25)),
            rate_export=float(env.get("RATE_EXPORT", 0.08)),
            tz=env.get("TZ", "America/Los_Angeles"),
            out_dir=out / "grafana" / "dashboards",
        )

    print(f"Stack generated for {len(gateways)} gateway(s): "
          + ", ".join(g["tag"] for g in gateways))


if __name__ == "__main__":
    main()
